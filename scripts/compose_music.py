"""
An original score for the Sisyphus game, synthesised from scratch (no samples,
no third-party material): ancient-Greek in colour — E phrygian, 7/8 grouped
3+2+2 at a quick dance pace, a plucked lyre ostinato, an aulos (double reed)
melody over a drone, davul and frame drums with jingles and finger cymbals,
and strings, horns and a wordless choir for the climaxes.
Every sound here is generated by this script, so the result is free of any
third-party copyright.

usage: python3 scripts/compose_music.py out.wav 3
       python3 scripts/master_music.py out.wav mastered.wav -10.8
       ffmpeg -i mastered.wav -b:a 160k public/music.mp3
"""
import sys
import numpy as np
from scipy import signal

SR = 44100
BPM = 80.75
BEAT = 60.0 / BPM
BAR = BEAT * 4
rng = np.random.default_rng(int(sys.argv[2]) if len(sys.argv) > 2 else 7)

N_BARS = 68
LEN = int(N_BARS * BAR * SR) + SR * 6
L = np.zeros(LEN)
R = np.zeros(LEN)


def midi(n):
    return 440.0 * 2 ** ((n - 69) / 12)


def place(buf, start_s, x, gain=1.0):
    i = int(start_s * SR)
    if i >= len(buf):
        return
    n = min(len(x), len(buf) - i)
    buf[i : i + n] += x[:n] * gain


def add(start_s, x, gain=1.0, pan=0.0):
    """pan -1..1, equal power"""
    a = (pan + 1) * np.pi / 4
    place(L, start_s, x, gain * np.cos(a))
    place(R, start_s, x, gain * np.sin(a))


def env_adsr(n, a, d, s, r, sr=SR):
    a, d, r = int(a * sr), int(d * sr), int(r * sr)
    sus = max(0, n - a - d - r)
    e = np.concatenate(
        [
            np.linspace(0, 1, max(1, a)),
            np.linspace(1, s, max(1, d)),
            np.full(sus, s),
            np.linspace(s, 0, max(1, r)),
        ]
    )
    return e[:n] if len(e) >= n else np.pad(e, (0, n - len(e)))


def saw(freq, n, detune_cents=0.0, phase=None):
    t = np.arange(n) / SR
    f = freq * 2 ** (detune_cents / 1200)
    ph = rng.random() if phase is None else phase
    return 2 * ((t * f + ph) % 1.0) - 1


def lowpass(x, cutoff, order=2):
    cutoff = min(cutoff, SR * 0.45)
    b, a = signal.butter(order, cutoff / (SR / 2), "low")
    return signal.lfilter(b, a, x)


def bandpass(x, lo, hi, order=2):
    b, a = signal.butter(order, [lo / (SR / 2), min(hi, SR * 0.45) / (SR / 2)], "band")
    return signal.lfilter(b, a, x)


# ---------------------------------------------------------------- instruments
def string_section(note, dur, vel=1.0, attack=0.02, release=0.25, bright=1.0, voices=5):
    n = int((dur + release) * SR)
    f = midi(note)
    x = np.zeros(n)
    for v in range(voices):
        cents = (v - (voices - 1) / 2) * 7 + rng.normal(0, 2)
        x += saw(f, n, cents)
    x /= voices
    # bow noise and a gentle vibrato via a slight wobble filter
    x = lowpass(x, f * (4 + 6 * bright), 2)
    x += lowpass(rng.normal(0, 0.02, n), 3000) * bright
    e = env_adsr(n, attack, 0.08, 0.8, release)
    return x * e * vel


def pad(notes, dur, vel=1.0):
    n = int((dur + 2.5) * SR)
    x = np.zeros(n)
    t = np.arange(n) / SR
    for note in notes:
        f = midi(note)
        for v in range(6):
            cents = (v - 2.5) * 6
            vib = 1 + 0.003 * np.sin(2 * np.pi * (5.2 + v * 0.13) * t + v)
            ph = np.cumsum(f * 2 ** (cents / 1200) * vib) / SR + rng.random()
            x += 2 * (ph % 1.0) - 1
    x /= 6 * len(notes)
    x = lowpass(x, 1800, 2)
    e = env_adsr(n, 1.4, 0.5, 0.85, 2.5)
    return x * e * vel * 1.7


def horn(note, dur, vel=1.0):
    n = int((dur + 0.5) * SR)
    t = np.arange(n) / SR
    f = midi(note)
    vib = 1 + 0.004 * np.sin(2 * np.pi * 4.8 * t) * np.clip(t / 0.6, 0, 1)
    ph = np.cumsum(f * vib) / SR
    x = 0.6 * (2 * (ph % 1) - 1) + 0.4 * (2 * ((ph * 1.003 + 0.3) % 1) - 1)
    e = env_adsr(n, 0.12, 0.2, 0.85, 0.5)
    # brightness follows loudness, as a brass player's does
    bright = lowpass(x, f * 3.2, 2) * (1 - e * 0.4) + lowpass(x, f * 7, 2) * e * 0.4
    return bright * e * vel * 1.9


def choir(notes, dur, vel=1.0, vowel="a"):
    """a wordless choir: buzz through vowel formants, many slightly detuned voices"""
    n = int((dur + 2.0) * SR)
    t = np.arange(n) / SR
    src = np.zeros(n)
    for note in notes:
        f = midi(note)
        for v in range(4):
            vib = 1 + 0.006 * np.sin(2 * np.pi * (5.5 + v * 0.3) * t + v * 1.7)
            ph = np.cumsum(f * 2 ** (((v - 1.5) * 9) / 1200) * vib) / SR + rng.random()
            src += 2 * (ph % 1) - 1
    src /= 4 * len(notes)
    formants = {"a": [(800, 1150, 1.0), (1150, 1500, 0.5), (2800, 3200, 0.2)],
                "o": [(400, 650, 1.0), (750, 950, 0.5), (2400, 2800, 0.15)]}[vowel]
    x = sum(bandpass(src, lo, hi) * g for lo, hi, g in formants)
    x += lowpass(rng.normal(0, 0.01, n), 4000)  # breath
    e = env_adsr(n, 1.2, 0.4, 0.9, 2.0)
    return x * e * vel * 3.6


def taiko(vel=1.0, pitch=58.0, decay=0.55):
    n = int(1.6 * SR)
    t = np.arange(n) / SR
    f = pitch * (1 + 1.6 * np.exp(-t * 28))
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / decay)
    skin = lowpass(rng.normal(0, 1, n), 1800) * np.exp(-t * 35) * 0.5
    thump = np.sin(2 * np.pi * 34 * t) * np.exp(-t / (decay * 1.4)) * 0.6
    return np.tanh((body * 1.0 + skin * 1.4 + thump * 0.7) * 1.3) * vel * 0.8


def frame_drum(vel=1.0):
    n = int(0.6 * SR)
    t = np.arange(n) / SR
    f = 140 * (1 + 0.8 * np.exp(-t * 40))
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 9)
    x += bandpass(rng.normal(0, 1, n), 800, 5000) * np.exp(-t * 30) * 0.35
    return x * vel


def swell(dur, vel=1.0):
    """a cymbal swell: filtered noise, rising, cut off at the downbeat"""
    n = int(dur * SR)
    t = np.linspace(0, 1, n)
    x = bandpass(rng.normal(0, 1, n), 3000, 14000) * t ** 3
    return x * vel


def boom(vel=1.0):
    """a deep cinematic hit for section changes"""
    n = int(4 * SR)
    t = np.arange(n) / SR
    f = 42 * (1 + 2.5 * np.exp(-t * 18))
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 1.4)
    x += lowpass(rng.normal(0, 1, n), 600) * np.exp(-t * 6) * 0.4
    return np.tanh(x * 1.6) * vel * 0.45


def reed(note, dur, vel=1.0):
    """a duduk/ney-like reed: a narrow, breathy double-reed tone with a slow
    vibrato that opens up as the note is held, and a scoop into the pitch"""
    n = int((dur + 0.35) * SR)
    t = np.arange(n) / SR
    f = midi(note)
    scoop = 1 - 0.025 * np.exp(-t * 14)
    vib = 1 + 0.006 * np.sin(2 * np.pi * 5.6 * t) * np.clip((t - 0.25) / 0.8, 0, 1)
    ph = np.cumsum(f * scoop * vib) / SR
    sq = np.tanh(np.sin(2 * np.pi * ph) * 2.2) * 0.8 + 0.2 * np.sin(4 * np.pi * ph)
    x = bandpass(sq, f * 0.9, f * 5, 2) + bandpass(sq, 1000, 1800, 2) * 0.25
    x += bandpass(rng.normal(0, 1, n), 1200, 5000) * 0.03  # breath
    e = env_adsr(n, 0.09, 0.15, 0.85, 0.3)
    return x * e * vel * 1.5


# ================================================================ ancient Greece
# 7/8, grouped 3+2+2 — the limping, driving metre of Greek dance — at a quick
# pace. E phrygian (the old Dorian), lyre and aulos over big frame drums.
EIGHTH = 60.0 / 268.0
BAR = EIGHTH * 7
BEAT = EIGHTH * 2  # used by swell(); a "beat" here is two eighths
GROUPS = [0, 3, 5]  # where the three pulses of the bar fall, in eighths
SECTIONS = [(8, "intro"), (24, "A"), (20, "B"), (10, "bridge"), (24, "A2"), (24, "climax"), (8, "outro")]
N_BARS = sum(b for b, _ in SECTIONS)
LEN = int(N_BARS * BAR * SR) + SR * 6
L = np.zeros(LEN)
R = np.zeros(LEN)

_lyre_cache = {}


def lyre(note, dur, vel=1.0, bright=1.0):
    """a plucked gut string: decaying harmonics, the high ones dying first, a
    pluck-position comb, and a short noisy attack"""
    key = (note, round(dur, 2), round(bright, 2))
    if key not in _lyre_cache:
        n = int((dur + 1.2) * SR)
        t = np.arange(n) / SR
        f = midi(note)
        x = np.zeros(n)
        pos = 0.18  # where along the string it is plucked
        for h in range(1, 14):
            fh = f * h * (1 + 0.0004 * h * h)  # a little inharmonicity
            if fh > SR * 0.45:
                break
            amp = abs(np.sin(np.pi * h * pos)) / h ** (1.1 - 0.25 * bright)
            decay = 1.8 / (1 + 0.55 * (h - 1) ** 1.3)
            x += amp * np.sin(2 * np.pi * fh * t + h) * np.exp(-t / decay)
        x += lowpass(np.random.default_rng(note).normal(0, 1, n), 4000) * np.exp(-t * 90) * 0.15
        x *= np.clip(t / 0.002, 0, 1)
        x *= np.minimum(1, np.maximum(0, (dur + 1.2 - t) / 0.3))
        _lyre_cache[key] = x / (np.max(np.abs(x)) + 1e-9)
    return _lyre_cache[key] * vel


def aulos(note, dur, vel=1.0):
    """the aulos: two reed pipes, buzzier than a duduk, one carrying the tune and
    one a drone; here the melody pipe, bright and nasal"""
    n = int((dur + 0.15) * SR)
    t = np.arange(n) / SR
    f = midi(note)
    vib = 1 + 0.004 * np.sin(2 * np.pi * 6.2 * t) * np.clip((t - 0.15) / 0.4, 0, 1)
    ph = np.cumsum(f * vib * (1 - 0.015 * np.exp(-t * 30))) / SR
    x = np.tanh(np.sin(2 * np.pi * ph) * 4.0) + 0.35 * np.tanh(np.sin(2 * np.pi * ph * 2.0 + 0.4) * 3.0)
    x = bandpass(x, f * 0.9, 6000, 2) + bandpass(x, 1100, 2200, 2) * 0.5
    x += bandpass(np.random.default_rng(note).normal(0, 1, n), 2000, 7000) * 0.025
    e = env_adsr(n, 0.025, 0.05, 0.9, 0.12)
    return x * e * vel


def davul(vel=1.0, low=True):
    """the big two-headed drum: a deep boom on one head, a dry slap on the other"""
    n = int(1.0 * SR)
    t = np.arange(n) / SR
    if low:
        f = 62 * (1 + 1.2 * np.exp(-t * 30))
        x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.32)
        x += lowpass(rng.normal(0, 1, n), 900) * np.exp(-t * 45) * 0.6
    else:
        f = 190 * (1 + 0.5 * np.exp(-t * 60))
        x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 22) * 0.6
        x += bandpass(rng.normal(0, 1, n), 1200, 7000) * np.exp(-t * 40) * 0.8
    return np.tanh(x * 1.5) * vel * (1.25 if low else 1.0)


def jingles(vel=1.0):
    """tambourine / sistrum: a burst of bright metal"""
    n = int(0.25 * SR)
    t = np.arange(n) / SR
    x = bandpass(rng.normal(0, 1, n), 5000, 14000) * np.exp(-t * 28)
    x += sum(np.sin(2 * np.pi * f0 * t) for f0 in (6100, 7400, 8900)) * np.exp(-t * 35) * 0.05
    return x * vel * 0.55


def kymbala(vel=1.0):
    """small finger cymbals: a pure ring"""
    n = int(1.2 * SR)
    t = np.arange(n) / SR
    x = sum(np.sin(2 * np.pi * f0 * t + i) * a for i, (f0, a) in enumerate([(2350, 1), (3920, 0.6), (5480, 0.35)]))
    return x * np.exp(-t * 3.2) * vel * 0.4


# E phrygian. Chord roots for each bar, a two-bar harmonic rhythm.
E = 40  # E2
CH = {
    "Em": (E, [52, 55, 59, 64]),
    "F": (E + 1, [53, 57, 60, 65]),
    "G": (E + 3, [55, 59, 62, 67]),
    "Dm": (E - 2, [50, 53, 57, 62]),
    "Am": (E + 5, [57, 60, 64, 69]),
    "C": (E - 4, [48, 52, 55, 60]),
}
PROG_A = ["Em", "Em", "F", "F", "G", "G", "F", "Em"]
PROG_B = ["Am", "Am", "G", "G", "F", "F", "Em", "Em"]
PROG_C = ["Em", "F", "G", "F", "Am", "G", "F", "Em"]

# lyre ostinato over 7 eighths, scale steps above the chord root (3+2+2)
LYRE_PAT = [0, 7, 12, 3, 7, 10, 7]
# the aulos tune, (midi, eighths); every two bars = 14 eighths
TUNE_A = [(64, 3), (65, 2), (67, 2), (69, 3), (67, 2), (65, 2),
          (64, 3), (62, 2), (64, 2), (65, 4), (64, 3),
          (67, 3), (69, 2), (71, 2), (72, 3), (71, 2), (69, 2),
          (67, 2), (69, 1), (67, 2), (65, 2), (64, 7)]
TUNE_B = [(69, 3), (72, 2), (71, 2), (69, 3), (67, 2), (65, 2),
          (67, 3), (69, 2), (67, 2), (65, 3), (64, 4),
          (65, 3), (67, 2), (69, 2), (71, 3), (72, 2), (74, 2),
          (72, 2), (71, 2), (69, 3), (67, 3), (64, 4)]


def bar_time(b):
    return b * BAR


def drums(t0, level, kind):
    if kind == "light":
        add(t0, davul(0.5 * level), 1.0, 0)
        for g in GROUPS[1:]:
            add(t0 + g * EIGHTH, frame_drum(0.18 * level), 1.0, 0.3)
        return
    # full: boom on 1, slaps on the 2 and 2, ghost notes between, jingles on the pulses
    add(t0, davul(0.95 * level), 1.0, 0)
    add(t0 + 3 * EIGHTH, davul(0.55 * level, low=False), 1.0, 0.25)
    add(t0 + 5 * EIGHTH, davul(0.6 * level, low=False), 1.0, -0.25)
    if kind == "heavy":
        add(t0 + 5 * EIGHTH, taiko(0.55 * level, 58), 1.0, 0)
        add(t0 + 6 * EIGHTH, davul(0.5 * level), 1.0, 0)
    for e8 in range(7):
        acc = e8 in GROUPS
        add(t0 + e8 * EIGHTH, jingles((0.16 if acc else 0.08) * level), 1.0, 0.45 if e8 % 2 else -0.45)
        if not acc:
            add(t0 + e8 * EIGHTH, frame_drum(0.12 * level), 1.0, 0.3)


b0 = 0
for bars, name in SECTIONS:
    prog = PROG_B if name in ("B",) else PROG_C if name == "climax" else PROG_A
    for k in range(bars):
        b = b0 + k
        t0 = bar_time(b)
        root, chord = CH[prog[k % 8]] if name not in ("intro", "bridge", "outro") else CH["Em" if k % 4 < 2 else "F"]
        level = {"intro": 0.6, "A": 0.85, "B": 0.95, "bridge": 0.7, "A2": 0.9, "climax": 1.0, "outro": 0.6}[name]

        # drone: the aulos's second pipe and a low string, on E and B
        add(t0, string_section(E, BAR, 0.08 * level, attack=0.3, release=0.6, bright=0.5, voices=3), 1.0, -0.1)
        add(t0, aulos(E + 19, BAR * 0.98, 0.05 * level), 1.0, 0.2)

        # lyre: an eighth-note ostinato through the chord, every bar
        for e8, step in enumerate(LYRE_PAT):
            note = root + 24 + step
            acc = 1.0 if e8 in GROUPS else 0.7
            add(t0 + e8 * EIGHTH, lyre(note, EIGHTH * 2, 0.22 * level * acc), 1.0, 0.35)
            if name in ("A2", "climax"):
                add(t0 + e8 * EIGHTH, lyre(note + 12, EIGHTH * 1.5, 0.10 * level * acc, 1.3), 1.0, -0.4)

        # pad and low strings under it all except the intro
        if name != "intro":
            add(t0, pad(chord, BAR, 0.14 * level), 1.0, -0.25)
        if name in ("B", "A2", "climax"):
            # driving low strings in eighths, accented 3+2+2
            for e8 in range(7):
                acc = 1.25 if e8 in GROUPS else 0.8
                add(t0 + e8 * EIGHTH, string_section(root + 12 + (7 if e8 == 6 else 0), EIGHTH * 0.85,
                                                     0.24 * level * acc, attack=0.004, release=0.05, voices=3),
                    1.0, -0.3)

        # drums
        if name == "intro":
            if k >= 2:
                drums(t0, 0.55 + 0.05 * k, "light")
        elif name == "bridge":
            drums(t0, 0.75, "light")
            if k % 2 == 0:
                add(t0, kymbala(0.5), 1.0, 0.3)
        elif name == "outro":
            drums(t0, 0.7 - 0.06 * k, "light")
        else:
            drums(t0, level, "heavy" if name in ("B", "climax") else "full")

        # fills into each section
        if k == bars - 1 and name != "outro":
            add(t0 + 3 * EIGHTH, swell(EIGHTH * 4, 0.12), 1.0, 0)
            for i in range(7):
                add(t0 + i * EIGHTH, davul(0.45 + 0.07 * i, low=i % 2 == 0), 1.0, -0.3 + 0.1 * i)

    if name in ("A", "B", "climax", "A2"):
        add(bar_time(b0), boom(0.55), 1.0, 0)
        add(bar_time(b0), kymbala(0.7), 1.0, -0.2)

    # melodies
    def play(tune, start_bar, reps, inst, gain, shift=0, pan=0.1):
        t = bar_time(start_bar)
        for _ in range(reps):
            for note, e8 in tune:
                add(t, inst(note + shift, e8 * EIGHTH * 0.95, gain), 1.0, pan)
                t += e8 * EIGHTH

    if name == "A":
        play(TUNE_A, b0 + 4, 2, aulos, 0.20)
        play(TUNE_A, b0 + 12, 1, aulos, 0.20)  # 4 bars per tune pass
        play(TUNE_A, b0 + 16, 2, aulos, 0.22)
    if name == "B":
        play(TUNE_B, b0, 5, horn, 0.30, -12, 0.15)
        play(TUNE_B, b0 + 8, 3, aulos, 0.16)
        for kk in range(0, bars, 2):
            r, c = CH[PROG_B[kk % 8]]
            add(bar_time(b0 + kk), choir([c[0] + 12, c[1] + 12, c[3] + 12], BAR * 2, 0.18, "a"), 1.0, -0.1)
    if name == "bridge":
        # the lyre alone, a slow free line above the ostinato
        t = bar_time(b0 + 2)
        for note, e8 in [(76, 7), (77, 3), (76, 4), (74, 7), (72, 7), (71, 3), (72, 4), (74, 7), (76, 14)]:
            add(t, lyre(note, e8 * EIGHTH, 0.35, 1.2), 1.0, -0.1)
            t += e8 * EIGHTH
    if name == "A2":
        play(TUNE_A, b0, 6, aulos, 0.22)
        play(TUNE_A, b0 + 8, 4, horn, 0.22, -12, -0.15)
    if name == "climax":
        play(TUNE_B, b0, 6, horn, 0.34, 0, 0.15)
        play(TUNE_B, b0, 6, horn, 0.2, -12, -0.2)
        play(TUNE_A, b0 + 12, 3, aulos, 0.2, 12)
        for kk in range(0, bars, 2):
            r, c = CH[PROG_C[kk % 8]]
            add(bar_time(b0 + kk), choir([c[0] + 12, c[2] + 12, c[3] + 12], BAR * 2, 0.22, "a"), 1.0, -0.1)
    if name == "outro":
        add(bar_time(b0), choir([64, 67, 71], BAR * 6, 0.14, "o"), 1.0, 0)
        play([(76, 7), (74, 3), (72, 4), (71, 7), (76, 21)], b0, 1, aulos, 0.16)
    b0 += bars

# ---------------------------------------------------------------- mix
def reverb(x, seconds=3.2, wet=0.28, seed=0):
    r = np.random.default_rng(seed)
    n = int(seconds * SR)
    t = np.arange(n) / SR
    ir = r.normal(0, 1, n) * np.exp(-t * 6.9 / seconds)
    ir = lowpass(ir, 6000)
    ir[: int(0.012 * SR)] *= np.linspace(0, 1, int(0.012 * SR))  # pre-delay softness
    ir /= np.sqrt(np.sum(ir ** 2))
    y = signal.fftconvolve(x, ir)[: len(x)]
    return x * (1 - wet) + y * wet * 1.6


L2 = reverb(L, seed=1)
R2 = reverb(R, seed=2)
# gentle master: high-pass the rumble, soft-clip, normalise
b, a = signal.butter(2, 45 / (SR / 2), "high")
L2 = signal.lfilter(b, a, L2)
R2 = signal.lfilter(b, a, R2)
# a little air and presence: a high shelf of +5 dB from ~2.5 kHz, built from a
# high-passed copy added back in
bh, ah = signal.butter(1, 2500 / (SR / 2), "high")
bm, am = signal.butter(2, [700 / (SR / 2), 2200 / (SR / 2)], "band")
L2 = L2 + 0.8 * signal.lfilter(bh, ah, L2) + 0.35 * signal.lfilter(bm, am, L2)
R2 = R2 + 0.8 * signal.lfilter(bh, ah, R2) + 0.35 * signal.lfilter(bm, am, R2)
peak = max(np.max(np.abs(L2)), np.max(np.abs(R2)))
L2, R2 = L2 / peak * 1.4, R2 / peak * 1.4
