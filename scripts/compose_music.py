"""
An original cinematic score for the Sisyphus game, synthesised from scratch
(no samples, no third-party material): D minor, 84 bpm, a driving low-string
ostinato, taiko-style drums, string pads, a horn theme and a wordless choir.
Every sound here is generated by this script, so the result is free of any
third-party copyright.

usage: python3 scripts/compose_music.py out.wav 11
       ffmpeg -i out.wav -b:a 160k public/music.mp3
(seed 11 is the version in the game)
"""
import sys
import numpy as np
from scipy import signal

SR = 44100
BPM = 68.0
BEAT = 60.0 / BPM
BAR = BEAT * 4
rng = np.random.default_rng(int(sys.argv[2]) if len(sys.argv) > 2 else 7)

N_BARS = 72
LEN = int(N_BARS * BAR * SR) + SR * 6
L = np.zeros(LEN)
R = np.zeros(LEN)


def midi(n):
    return 440.0 * 2 ** ((n - 69) / 12)


def place(buf, start_s, x, gain=1.0):
    i = int(start_s * SR)
    if i >= len(buf):
        return
    n = min(len(x), len(buf) - i)
    buf[i : i + n] += x[:n] * gain


def add(start_s, x, gain=1.0, pan=0.0):
    """pan -1..1, equal power"""
    a = (pan + 1) * np.pi / 4
    place(L, start_s, x, gain * np.cos(a))
    place(R, start_s, x, gain * np.sin(a))


def env_adsr(n, a, d, s, r, sr=SR):
    a, d, r = int(a * sr), int(d * sr), int(r * sr)
    sus = max(0, n - a - d - r)
    e = np.concatenate(
        [
            np.linspace(0, 1, max(1, a)),
            np.linspace(1, s, max(1, d)),
            np.full(sus, s),
            np.linspace(s, 0, max(1, r)),
        ]
    )
    return e[:n] if len(e) >= n else np.pad(e, (0, n - len(e)))


def saw(freq, n, detune_cents=0.0, phase=None):
    t = np.arange(n) / SR
    f = freq * 2 ** (detune_cents / 1200)
    ph = rng.random() if phase is None else phase
    return 2 * ((t * f + ph) % 1.0) - 1


def lowpass(x, cutoff, order=2):
    cutoff = min(cutoff, SR * 0.45)
    b, a = signal.butter(order, cutoff / (SR / 2), "low")
    return signal.lfilter(b, a, x)


def bandpass(x, lo, hi, order=2):
    b, a = signal.butter(order, [lo / (SR / 2), min(hi, SR * 0.45) / (SR / 2)], "band")
    return signal.lfilter(b, a, x)


# ---------------------------------------------------------------- instruments
def string_section(note, dur, vel=1.0, attack=0.02, release=0.25, bright=1.0, voices=5):
    n = int((dur + release) * SR)
    f = midi(note)
    x = np.zeros(n)
    for v in range(voices):
        cents = (v - (voices - 1) / 2) * 7 + rng.normal(0, 2)
        x += saw(f, n, cents)
    x /= voices
    # bow noise and a gentle vibrato via a slight wobble filter
    x = lowpass(x, f * (4 + 6 * bright), 2)
    x += lowpass(rng.normal(0, 0.02, n), 3000) * bright
    e = env_adsr(n, attack, 0.08, 0.8, release)
    return x * e * vel


def pad(notes, dur, vel=1.0):
    n = int((dur + 2.5) * SR)
    x = np.zeros(n)
    t = np.arange(n) / SR
    for note in notes:
        f = midi(note)
        for v in range(6):
            cents = (v - 2.5) * 6
            vib = 1 + 0.003 * np.sin(2 * np.pi * (5.2 + v * 0.13) * t + v)
            ph = np.cumsum(f * 2 ** (cents / 1200) * vib) / SR + rng.random()
            x += 2 * (ph % 1.0) - 1
    x /= 6 * len(notes)
    x = lowpass(x, 1800, 2)
    e = env_adsr(n, 1.4, 0.5, 0.85, 2.5)
    return x * e * vel * 1.7


def horn(note, dur, vel=1.0):
    n = int((dur + 0.5) * SR)
    t = np.arange(n) / SR
    f = midi(note)
    vib = 1 + 0.004 * np.sin(2 * np.pi * 4.8 * t) * np.clip(t / 0.6, 0, 1)
    ph = np.cumsum(f * vib) / SR
    x = 0.6 * (2 * (ph % 1) - 1) + 0.4 * (2 * ((ph * 1.003 + 0.3) % 1) - 1)
    e = env_adsr(n, 0.12, 0.2, 0.85, 0.5)
    # brightness follows loudness, as a brass player's does
    bright = lowpass(x, f * 3.2, 2) * (1 - e * 0.4) + lowpass(x, f * 7, 2) * e * 0.4
    return bright * e * vel * 1.9


def choir(notes, dur, vel=1.0, vowel="a"):
    """a wordless choir: buzz through vowel formants, many slightly detuned voices"""
    n = int((dur + 2.0) * SR)
    t = np.arange(n) / SR
    src = np.zeros(n)
    for note in notes:
        f = midi(note)
        for v in range(4):
            vib = 1 + 0.006 * np.sin(2 * np.pi * (5.5 + v * 0.3) * t + v * 1.7)
            ph = np.cumsum(f * 2 ** (((v - 1.5) * 9) / 1200) * vib) / SR + rng.random()
            src += 2 * (ph % 1) - 1
    src /= 4 * len(notes)
    formants = {"a": [(800, 1150, 1.0), (1150, 1500, 0.5), (2800, 3200, 0.2)],
                "o": [(400, 650, 1.0), (750, 950, 0.5), (2400, 2800, 0.15)]}[vowel]
    x = sum(bandpass(src, lo, hi) * g for lo, hi, g in formants)
    x += lowpass(rng.normal(0, 0.01, n), 4000)  # breath
    e = env_adsr(n, 1.2, 0.4, 0.9, 2.0)
    return x * e * vel * 3.6


def taiko(vel=1.0, pitch=58.0, decay=0.55):
    n = int(1.6 * SR)
    t = np.arange(n) / SR
    f = pitch * (1 + 1.6 * np.exp(-t * 28))
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / decay)
    skin = lowpass(rng.normal(0, 1, n), 1800) * np.exp(-t * 35) * 0.5
    thump = np.sin(2 * np.pi * 34 * t) * np.exp(-t / (decay * 1.4)) * 0.6
    return np.tanh((body * 0.8 + skin * 1.6 + thump * 0.5) * 1.3) * vel * 0.32


def frame_drum(vel=1.0):
    n = int(0.6 * SR)
    t = np.arange(n) / SR
    f = 140 * (1 + 0.8 * np.exp(-t * 40))
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 9)
    x += bandpass(rng.normal(0, 1, n), 800, 5000) * np.exp(-t * 30) * 0.35
    return x * vel


def swell(dur, vel=1.0):
    """a cymbal swell: filtered noise, rising, cut off at the downbeat"""
    n = int(dur * SR)
    t = np.linspace(0, 1, n)
    x = bandpass(rng.normal(0, 1, n), 3000, 14000) * t ** 3
    return x * vel


def boom(vel=1.0):
    """a deep cinematic hit for section changes"""
    n = int(4 * SR)
    t = np.arange(n) / SR
    f = 42 * (1 + 2.5 * np.exp(-t * 18))
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 1.4)
    x += lowpass(rng.normal(0, 1, n), 600) * np.exp(-t * 6) * 0.4
    return np.tanh(x * 1.6) * vel * 0.45


# ---------------------------------------------------------------- harmony
# i  VI  III  VII  in D minor, and a darker iv-v turn for the bridge
PROG_A = [(38, [50, 53, 57, 62]), (34, [46, 50, 53, 58]), (41, [48, 53, 57, 60]), (36, [48, 52, 55, 60])]
PROG_B = [(38, [50, 53, 57, 62]), (43, [50, 55, 58, 62]), (34, [46, 50, 53, 58]), (33, [45, 49, 52, 57])]
# the ostinato: 16ths, root-heavy, with a lift to the fifth
OST = [0, 7, 12, 7, 3, 7, 12, 7, 0, 7, 10, 7, 3, 7, 5, 7]

# a horn theme in D minor (MIDI notes, beats)
THEME = [(62, 1.5), (65, 0.5), (64, 1), (62, 1), (69, 3), (67, 1),
         (65, 1.5), (64, 0.5), (62, 1), (60, 1), (62, 4),
         (62, 1.5), (65, 0.5), (69, 1), (70, 1), (72, 2), (70, 1), (69, 1),
         (67, 1.5), (65, 0.5), (64, 1), (61, 1), (62, 4)]

# section plan: (bars, name)
SECTIONS = [(8, "intro"), (8, "build"), (16, "A"), (8, "bridge"), (16, "climax"), (8, "fall"), (8, "outro")]


def bar_time(b):
    return b * BAR


b0 = 0
for bars, name in SECTIONS:
    for k in range(bars):
        b = b0 + k
        t0 = bar_time(b)
        prog = PROG_B if name == "bridge" else PROG_A
        root, chord = prog[(b // 1) % 4] if name != "intro" else prog[(b // 2) % 4]
        last_bar = k == bars - 1

        # strings pad, every bar (two-bar chords in the intro)
        if name == "intro":
            if k % 2 == 0:
                add(t0, pad(chord, BAR * 2, 0.22 + 0.02 * k), 1.0, -0.2)
                add(t0, pad([root + 12], BAR * 2, 0.10), 1.0, 0.3)
        else:
            lvl = {"build": 0.2, "A": 0.24, "bridge": 0.2, "climax": 0.3, "fall": 0.2, "outro": 0.18}[name]
            add(t0, pad(chord, BAR, lvl), 1.0, -0.25)
            add(t0, pad([n + 12 for n in chord[1:3]], BAR, lvl * 0.5), 1.0, 0.35)

        # the ostinato: cellos and basses in 16ths
        if name in ("build", "A", "bridge", "climax", "fall"):
            ost_lvl = {"build": 0.10 + 0.02 * k, "A": 0.26, "bridge": 0.2, "climax": 0.32, "fall": 0.22 - 0.02 * k}[name]
            step = BEAT / 4
            for i in range(16):
                interval = OST[i]
                note = root + interval
                accent = 1.25 if i % 4 == 0 else 0.85
                x = string_section(note, step * 0.9, ost_lvl * accent, attack=0.006, release=0.06,
                                   bright=0.6 if name == "build" else 1.0, voices=3)
                add(t0 + i * step, x, 1.0, -0.35 + 0.1 * (i % 2))
                if name in ("A", "climax"):
                    x2 = string_section(note + 12, step * 0.8, ost_lvl * 0.45 * accent, attack=0.006,
                                        release=0.05, voices=3)
                    add(t0 + i * step, x2, 1.0, 0.4)

        # low drones under the bridge and intro
        if name in ("intro", "bridge", "outro"):
            add(t0, string_section(root - 12, BAR, 0.07, attack=0.8, release=1.2, bright=0.4, voices=4), 1.0, 0)

        # drums
        if name == "intro" and k >= 4:
            add(t0, taiko(0.35 + 0.08 * (k - 4), 52, 0.9), 1.0, 0)
        if name == "build":
            add(t0, taiko(0.55, 55), 1.0, -0.1)
            add(t0 + BEAT * 2, taiko(0.45, 60), 1.0, 0.1)
            if k >= 4:
                for i in range(8):
                    add(t0 + i * BEAT / 2, frame_drum(0.12 + 0.03 * (i % 2 == 0)), 1.0, 0.3)
        if name in ("A", "climax"):
            hit = 0.75 if name == "A" else 0.95
            # a driving taiko pattern: 1 . (2&) 3 . 4 (4e)(4&)
            for beat, v, p in [(0, 1.0, 55), (1.5, 0.6, 62), (2, 0.9, 55), (3, 0.7, 60), (3.5, 0.6, 66), (3.75, 0.5, 70)]:
                add(t0 + beat * BEAT, taiko(hit * v, p), 1.0, (p - 60) / 30)
            for i in range(16):
                if i % 4 != 0:
                    add(t0 + i * BEAT / 4, frame_drum(0.09 + 0.06 * (i % 2 == 0)), 1.0, 0.35 - 0.7 * (i % 3 == 0))
        if name == "bridge":
            add(t0, taiko(0.5, 50, 0.8), 1.0, 0)
            if k % 2 == 1:
                add(t0 + BEAT * 3, taiko(0.4, 58), 1.0, 0.2)
        if name == "fall":
            add(t0, taiko(0.6 - 0.06 * k, 52, 0.9), 1.0, 0)

        # fills and swells into section changes
        if last_bar and name not in ("outro",):
            add(t0 + BAR - BEAT * 2, swell(BEAT * 2, 0.10), 1.0, 0)
            if name in ("build", "A", "bridge"):
                for i, beat in enumerate([2.5, 3, 3.25, 3.5, 3.75]):
                    add(t0 + beat * BEAT, taiko(0.45 + 0.08 * i, 58 + i * 3), 1.0, -0.3 + 0.15 * i)

    # a hit on each new section
    if name in ("A", "climax", "bridge"):
        add(bar_time(b0), boom(0.55 if name != "bridge" else 0.4), 1.0, 0)

    # the horn theme over A (once) and climax (twice, the second an octave up with choir)
    if name in ("A", "climax"):
        reps = 1 if name == "A" else 2
        for r in range(reps):
            t = bar_time(b0 + r * 8)
            for note, beats in THEME:
                up = 12 if (name == "climax" and r == 1) else 0
                lvl = 0.30 if name == "A" else 0.36
                add(t, horn(note - 12 + up, beats * BEAT * 0.98, lvl), 1.0, 0.15)
                if name == "climax":
                    add(t, horn(note - 24 + up, beats * BEAT * 0.98, lvl * 0.5), 1.0, -0.2)
                t += beats * BEAT
    if name == "climax":
        for k in range(0, bars, 2):
            root, chord = PROG_A[k % 4]
            add(bar_time(b0 + k), choir([chord[0] + 12, chord[2] + 12, chord[3] + 12], BAR * 2, 0.20, "a"), 1.0, -0.1)
    if name == "bridge":
        for k in range(0, bars, 4):
            root, chord = PROG_B[0]
            add(bar_time(b0 + k), choir([62, 65, 69], BAR * 4, 0.16, "o"), 1.0, 0.1)
        # a solo cello line over the bridge
        t = bar_time(b0)
        for note, beats in [(57, 3), (58, 1), (57, 2), (55, 2), (53, 3), (52, 1), (50, 4),
                            (57, 3), (58, 1), (60, 2), (58, 2), (57, 4), (61, 4)]:
            add(t, string_section(note, beats * BEAT * 0.98, 0.22, attack=0.15, release=0.4, voices=2), 1.0, 0.25)
            t += beats * BEAT
    if name == "outro":
        add(bar_time(b0), choir([62, 65, 69], BAR * 6, 0.12, "o"), 1.0, 0)
        add(bar_time(b0 + 4), horn(50, BAR * 3, 0.22), 1.0, 0.1)
    b0 += bars

# ---------------------------------------------------------------- mix
def reverb(x, seconds=3.2, wet=0.28, seed=0):
    r = np.random.default_rng(seed)
    n = int(seconds * SR)
    t = np.arange(n) / SR
    ir = r.normal(0, 1, n) * np.exp(-t * 6.9 / seconds)
    ir = lowpass(ir, 6000)
    ir[: int(0.012 * SR)] *= np.linspace(0, 1, int(0.012 * SR))  # pre-delay softness
    ir /= np.sqrt(np.sum(ir ** 2))
    y = signal.fftconvolve(x, ir)[: len(x)]
    return x * (1 - wet) + y * wet * 1.6


L2 = reverb(L, seed=1)
R2 = reverb(R, seed=2)
# gentle master: high-pass the rumble, soft-clip, normalise
b, a = signal.butter(2, 45 / (SR / 2), "high")
L2 = signal.lfilter(b, a, L2)
R2 = signal.lfilter(b, a, R2)
# a little air and presence: a high shelf of +5 dB from ~2.5 kHz, built from a
# high-passed copy added back in
bh, ah = signal.butter(1, 2500 / (SR / 2), "high")
bm, am = signal.butter(2, [700 / (SR / 2), 2200 / (SR / 2)], "band")
L2 = L2 + 0.8 * signal.lfilter(bh, ah, L2) + 0.35 * signal.lfilter(bm, am, L2)
R2 = R2 + 0.8 * signal.lfilter(bh, ah, R2) + 0.35 * signal.lfilter(bm, am, R2)
peak = max(np.max(np.abs(L2)), np.max(np.abs(R2)))
L2, R2 = L2 / peak * 1.4, R2 / peak * 1.4
L2, R2 = np.tanh(L2) * 0.89, np.tanh(R2) * 0.89
# trim the tail and fade the ends for a clean loop
end = int(N_BARS * BAR * SR + 3 * SR)
L2, R2 = L2[:end], R2[:end]
fi, fo = int(0.05 * SR), int(3.0 * SR)
for ch in (L2, R2):
    ch[:fi] *= np.linspace(0, 1, fi)
    ch[-fo:] *= np.linspace(1, 0, fo) ** 2

from scipy.io import wavfile
out = np.stack([L2, R2], axis=1)
wavfile.write(sys.argv[1], SR, (out * 32767).astype(np.int16))
print("seconds", len(L2) / SR)
