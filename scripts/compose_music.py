"""
An original cinematic score for the Sisyphus game, synthesised from scratch
(no samples, no third-party material): C# hijaz, 80.75 bpm, a drone, a
driving low-string ostinato, taiko-style drums, a reed and a horn theme and a
wordless choir.
Every sound here is generated by this script, so the result is free of any
third-party copyright.

usage: python3 scripts/compose_music.py out.wav 5
       python3 scripts/master_music.py out.wav mastered.wav -10.8
       ffmpeg -i mastered.wav -b:a 160k public/music.mp3
"""
import sys
import numpy as np
from scipy import signal

SR = 44100
BPM = 80.75
BEAT = 60.0 / BPM
BAR = BEAT * 4
rng = np.random.default_rng(int(sys.argv[2]) if len(sys.argv) > 2 else 7)

N_BARS = 68
LEN = int(N_BARS * BAR * SR) + SR * 6
L = np.zeros(LEN)
R = np.zeros(LEN)


def midi(n):
    return 440.0 * 2 ** ((n - 69) / 12)


def place(buf, start_s, x, gain=1.0):
    i = int(start_s * SR)
    if i >= len(buf):
        return
    n = min(len(x), len(buf) - i)
    buf[i : i + n] += x[:n] * gain


def add(start_s, x, gain=1.0, pan=0.0):
    """pan -1..1, equal power"""
    a = (pan + 1) * np.pi / 4
    place(L, start_s, x, gain * np.cos(a))
    place(R, start_s, x, gain * np.sin(a))


def env_adsr(n, a, d, s, r, sr=SR):
    a, d, r = int(a * sr), int(d * sr), int(r * sr)
    sus = max(0, n - a - d - r)
    e = np.concatenate(
        [
            np.linspace(0, 1, max(1, a)),
            np.linspace(1, s, max(1, d)),
            np.full(sus, s),
            np.linspace(s, 0, max(1, r)),
        ]
    )
    return e[:n] if len(e) >= n else np.pad(e, (0, n - len(e)))


def saw(freq, n, detune_cents=0.0, phase=None):
    t = np.arange(n) / SR
    f = freq * 2 ** (detune_cents / 1200)
    ph = rng.random() if phase is None else phase
    return 2 * ((t * f + ph) % 1.0) - 1


def lowpass(x, cutoff, order=2):
    cutoff = min(cutoff, SR * 0.45)
    b, a = signal.butter(order, cutoff / (SR / 2), "low")
    return signal.lfilter(b, a, x)


def bandpass(x, lo, hi, order=2):
    b, a = signal.butter(order, [lo / (SR / 2), min(hi, SR * 0.45) / (SR / 2)], "band")
    return signal.lfilter(b, a, x)


# ---------------------------------------------------------------- instruments
def string_section(note, dur, vel=1.0, attack=0.02, release=0.25, bright=1.0, voices=5):
    n = int((dur + release) * SR)
    f = midi(note)
    x = np.zeros(n)
    for v in range(voices):
        cents = (v - (voices - 1) / 2) * 7 + rng.normal(0, 2)
        x += saw(f, n, cents)
    x /= voices
    # bow noise and a gentle vibrato via a slight wobble filter
    x = lowpass(x, f * (4 + 6 * bright), 2)
    x += lowpass(rng.normal(0, 0.02, n), 3000) * bright
    e = env_adsr(n, attack, 0.08, 0.8, release)
    return x * e * vel


def pad(notes, dur, vel=1.0):
    n = int((dur + 2.5) * SR)
    x = np.zeros(n)
    t = np.arange(n) / SR
    for note in notes:
        f = midi(note)
        for v in range(6):
            cents = (v - 2.5) * 6
            vib = 1 + 0.003 * np.sin(2 * np.pi * (5.2 + v * 0.13) * t + v)
            ph = np.cumsum(f * 2 ** (cents / 1200) * vib) / SR + rng.random()
            x += 2 * (ph % 1.0) - 1
    x /= 6 * len(notes)
    x = lowpass(x, 1800, 2)
    e = env_adsr(n, 1.4, 0.5, 0.85, 2.5)
    return x * e * vel * 1.7


def horn(note, dur, vel=1.0):
    n = int((dur + 0.5) * SR)
    t = np.arange(n) / SR
    f = midi(note)
    vib = 1 + 0.004 * np.sin(2 * np.pi * 4.8 * t) * np.clip(t / 0.6, 0, 1)
    ph = np.cumsum(f * vib) / SR
    x = 0.6 * (2 * (ph % 1) - 1) + 0.4 * (2 * ((ph * 1.003 + 0.3) % 1) - 1)
    e = env_adsr(n, 0.12, 0.2, 0.85, 0.5)
    # brightness follows loudness, as a brass player's does
    bright = lowpass(x, f * 3.2, 2) * (1 - e * 0.4) + lowpass(x, f * 7, 2) * e * 0.4
    return bright * e * vel * 1.9


def choir(notes, dur, vel=1.0, vowel="a"):
    """a wordless choir: buzz through vowel formants, many slightly detuned voices"""
    n = int((dur + 2.0) * SR)
    t = np.arange(n) / SR
    src = np.zeros(n)
    for note in notes:
        f = midi(note)
        for v in range(4):
            vib = 1 + 0.006 * np.sin(2 * np.pi * (5.5 + v * 0.3) * t + v * 1.7)
            ph = np.cumsum(f * 2 ** (((v - 1.5) * 9) / 1200) * vib) / SR + rng.random()
            src += 2 * (ph % 1) - 1
    src /= 4 * len(notes)
    formants = {"a": [(800, 1150, 1.0), (1150, 1500, 0.5), (2800, 3200, 0.2)],
                "o": [(400, 650, 1.0), (750, 950, 0.5), (2400, 2800, 0.15)]}[vowel]
    x = sum(bandpass(src, lo, hi) * g for lo, hi, g in formants)
    x += lowpass(rng.normal(0, 0.01, n), 4000)  # breath
    e = env_adsr(n, 1.2, 0.4, 0.9, 2.0)
    return x * e * vel * 3.6


def taiko(vel=1.0, pitch=58.0, decay=0.55):
    n = int(1.6 * SR)
    t = np.arange(n) / SR
    f = pitch * (1 + 1.6 * np.exp(-t * 28))
    body = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / decay)
    skin = lowpass(rng.normal(0, 1, n), 1800) * np.exp(-t * 35) * 0.5
    thump = np.sin(2 * np.pi * 34 * t) * np.exp(-t / (decay * 1.4)) * 0.6
    return np.tanh((body * 1.0 + skin * 1.4 + thump * 0.7) * 1.3) * vel * 0.8


def frame_drum(vel=1.0):
    n = int(0.6 * SR)
    t = np.arange(n) / SR
    f = 140 * (1 + 0.8 * np.exp(-t * 40))
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t * 9)
    x += bandpass(rng.normal(0, 1, n), 800, 5000) * np.exp(-t * 30) * 0.35
    return x * vel


def swell(dur, vel=1.0):
    """a cymbal swell: filtered noise, rising, cut off at the downbeat"""
    n = int(dur * SR)
    t = np.linspace(0, 1, n)
    x = bandpass(rng.normal(0, 1, n), 3000, 14000) * t ** 3
    return x * vel


def boom(vel=1.0):
    """a deep cinematic hit for section changes"""
    n = int(4 * SR)
    t = np.arange(n) / SR
    f = 42 * (1 + 2.5 * np.exp(-t * 18))
    x = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 1.4)
    x += lowpass(rng.normal(0, 1, n), 600) * np.exp(-t * 6) * 0.4
    return np.tanh(x * 1.6) * vel * 0.45


def reed(note, dur, vel=1.0):
    """a duduk/ney-like reed: a narrow, breathy double-reed tone with a slow
    vibrato that opens up as the note is held, and a scoop into the pitch"""
    n = int((dur + 0.35) * SR)
    t = np.arange(n) / SR
    f = midi(note)
    scoop = 1 - 0.025 * np.exp(-t * 14)
    vib = 1 + 0.006 * np.sin(2 * np.pi * 5.6 * t) * np.clip((t - 0.25) / 0.8, 0, 1)
    ph = np.cumsum(f * scoop * vib) / SR
    sq = np.tanh(np.sin(2 * np.pi * ph) * 2.2) * 0.8 + 0.2 * np.sin(4 * np.pi * ph)
    x = bandpass(sq, f * 0.9, f * 5, 2) + bandpass(sq, 1000, 1800, 2) * 0.25
    x += bandpass(rng.normal(0, 1, n), 1200, 5000) * 0.03  # breath
    e = env_adsr(n, 0.09, 0.15, 0.85, 0.3)
    return x * e * vel * 1.5


# ---------------------------------------------------------------- harmony
# C# hijaz (phrygian dominant): C# D F F# G# A B, with B# (C) as a leading tone.
# Mostly a drone on C# and G#, the bII (D) pulling against it, as in the
# world-music epic idiom.
C = 37  # C#2
PROG = [
    (C, [49, 53, 56, 61]),       # C#  (C# F G#)
    (C + 1, [50, 54, 57, 62]),   # D   (D F# A)
    (C, [49, 53, 56, 61]),       # C#
    (C - 2, [47, 50, 54, 59]),   # Bm  (B D F#)
]
# a 16th-note ostinato that worries at the semitone above and below the tonic
OST = [0, 0, 1, 0, 0, 0, -1, 0, 0, 0, 1, 0, 7, 4, 1, 0]

THEME_REED = [(73, 1), (74, 0.5), (77, 0.5), (78, 1), (80, 1.5), (78, 0.5), (77, 1), (74, 1), (73, 1),
              (77, 1), (78, 0.5), (80, 0.5), (81, 1), (80, 1), (78, 0.5), (77, 0.5), (74, 1), (73, 4),
              (80, 1), (81, 0.5), (80, 0.5), (78, 1), (77, 1), (78, 1), (77, 0.5), (74, 0.5), (73, 1), (72, 1),
              (73, 1.5), (74, 0.5), (77, 1), (74, 1), (73, 4)]
THEME_HORN = [(61, 2), (62, 1), (65, 1), (68, 3), (66, 1), (65, 1.5), (62, 0.5), (61, 2),
              (62, 1), (65, 1), (66, 1), (68, 1), (69, 2), (68, 1), (66, 1), (65, 2), (62, 1), (61, 1),
              (61, 4)]

SECTIONS = [(4, "intro"), (8, "build"), (16, "A"), (16, "B"), (4, "break"), (16, "A2"), (4, "outro")]
LEVEL = {"intro": 0.55, "build": 0.7, "A": 0.85, "B": 1.0, "break": 0.7, "A2": 0.95, "outro": 0.6}


def bar_time(b):
    return b * BAR


b0 = 0
for bars, name in SECTIONS:
    lv = LEVEL[name]
    for k in range(bars):
        b = b0 + k
        t0 = bar_time(b)
        root, chord = PROG[b % 4] if name not in ("intro", "break", "outro") else PROG[0]

        # the drone never stops: C# and G#, low and wide
        add(t0, string_section(C, BAR, 0.10 * lv, attack=0.6, release=1.0, bright=0.5, voices=4), 1.0, -0.15)
        add(t0, string_section(C + 7, BAR, 0.07 * lv, attack=0.6, release=1.0, bright=0.5, voices=4), 1.0, 0.15)

        # pads
        add(t0, pad(chord, BAR, 0.20 * lv), 1.0, -0.25)
        add(t0, pad([n + 12 for n in chord[1:3]], BAR, 0.10 * lv), 1.0, 0.35)

        # the ostinato, from the build on
        if name != "intro":
            step = BEAT / 4
            ost_lvl = (0.14 + 0.012 * k if name == "build" else 0.26) * lv
            for i in range(16):
                note = root + 12 + OST[i]
                accent = 1.3 if i % 4 == 0 else 0.85
                x = string_section(note, step * 0.85, ost_lvl * accent, attack=0.005, release=0.05, voices=3)
                add(t0 + i * step, x, 1.0, -0.3 + 0.12 * (i % 2))
                if name in ("A", "B", "A2"):
                    add(t0 + i * step, string_section(note + 12, step * 0.75, ost_lvl * 0.4 * accent,
                                                      attack=0.005, release=0.04, voices=3), 1.0, 0.4)

        # drums: always moving, heavier as it goes
        if name == "intro":
            add(t0, taiko(0.45, 52, 0.9), 1.0, 0)
            add(t0 + BEAT * 2.5, taiko(0.3, 58), 1.0, 0.15)
        elif name in ("build", "break"):
            for beat, v, p in [(0, 1.0, 54), (1.5, 0.55, 60), (2, 0.8, 56), (3, 0.6, 62)]:
                add(t0 + beat * BEAT, taiko(0.6 * v * lv + 0.03 * k, p), 1.0, (p - 58) / 25)
            for i in range(8):
                add(t0 + i * BEAT / 2, frame_drum(0.10 + 0.04 * (i % 2 == 0)), 1.0, 0.3)
        elif name in ("A", "B", "A2"):
            pat = [(0, 1.0, 54), (0.75, 0.45, 64), (1.5, 0.65, 60), (2, 0.9, 54), (2.5, 0.5, 66),
                   (3, 0.75, 58), (3.5, 0.6, 62), (3.75, 0.5, 68)]
            for beat, v, p in pat:
                add(t0 + beat * BEAT, taiko(0.95 * v * lv, p), 1.0, (p - 60) / 25)
            for i in range(16):
                if i % 4:
                    add(t0 + i * BEAT / 4, frame_drum(0.08 + 0.06 * (i % 2 == 0)), 1.0, 0.35 - 0.7 * (i % 3 == 0))
        elif name == "outro":
            add(t0, taiko(0.5 - 0.08 * k, 52, 0.9), 1.0, 0)

        if k == bars - 1 and name not in ("outro",):
            add(t0 + BAR - BEAT * 2, swell(BEAT * 2, 0.12), 1.0, 0)
            for i, beat in enumerate([2.5, 3, 3.25, 3.5, 3.75]):
                add(t0 + beat * BEAT, taiko(0.5 + 0.08 * i, 58 + i * 3), 1.0, -0.3 + 0.15 * i)

    if name in ("A", "B", "A2"):
        add(bar_time(b0), boom(0.6), 1.0, 0)

    # melodies
    if name in ("A", "A2"):
        for r in range(2 if name == "A" else 1):
            t = bar_time(b0 + r * 8)
            for note, beats in THEME_REED:
                add(t, reed(note - 12, beats * BEAT * 0.97, 0.30), 1.0, 0.1)
                t += beats * BEAT
    if name == "A2":
        t = bar_time(b0 + 8)
        for note, beats in THEME_HORN + THEME_HORN[:0]:
            add(t, horn(note, beats * BEAT * 0.98, 0.34), 1.0, 0.15)
            add(t, horn(note - 12, beats * BEAT * 0.98, 0.18), 1.0, -0.2)
            t += beats * BEAT
    if name == "B":
        for r in range(2):
            t = bar_time(b0 + r * 8)
            for note, beats in THEME_HORN:
                add(t, horn(note + (12 if r else 0), beats * BEAT * 0.98, 0.36), 1.0, 0.15)
                add(t, horn(note - 12 + (12 if r else 0), beats * BEAT * 0.98, 0.2), 1.0, -0.2)
                t += beats * BEAT
        for k in range(0, bars, 2):
            root, chord = PROG[k % 4]
            add(bar_time(b0 + k), choir([chord[0] + 12, chord[1] + 12, chord[3] + 12], BAR * 2, 0.22, "a"), 1.0, -0.1)
    if name == "intro":
        t = bar_time(b0)
        for note, beats in [(73, 3), (74, 1), (73, 4), (77, 2), (74, 2), (73, 4)]:
            add(t, reed(note - 12, beats * BEAT * 0.97, 0.22), 1.0, 0.1)
            t += beats * BEAT
    if name == "outro":
        add(bar_time(b0), choir([61, 65, 68], BAR * 4, 0.14, "o"), 1.0, 0)
        add(bar_time(b0), reed(61, BAR * 2, 0.22), 1.0, 0.1)
    b0 += bars

# ---------------------------------------------------------------- mix
def reverb(x, seconds=3.2, wet=0.28, seed=0):
    r = np.random.default_rng(seed)
    n = int(seconds * SR)
    t = np.arange(n) / SR
    ir = r.normal(0, 1, n) * np.exp(-t * 6.9 / seconds)
    ir = lowpass(ir, 6000)
    ir[: int(0.012 * SR)] *= np.linspace(0, 1, int(0.012 * SR))  # pre-delay softness
    ir /= np.sqrt(np.sum(ir ** 2))
    y = signal.fftconvolve(x, ir)[: len(x)]
    return x * (1 - wet) + y * wet * 1.6


L2 = reverb(L, seed=1)
R2 = reverb(R, seed=2)
# gentle master: high-pass the rumble, soft-clip, normalise
b, a = signal.butter(2, 45 / (SR / 2), "high")
L2 = signal.lfilter(b, a, L2)
R2 = signal.lfilter(b, a, R2)
# a little air and presence: a high shelf of +5 dB from ~2.5 kHz, built from a
# high-passed copy added back in
bh, ah = signal.butter(1, 2500 / (SR / 2), "high")
bm, am = signal.butter(2, [700 / (SR / 2), 2200 / (SR / 2)], "band")
L2 = L2 + 0.8 * signal.lfilter(bh, ah, L2) + 0.35 * signal.lfilter(bm, am, L2)
R2 = R2 + 0.8 * signal.lfilter(bh, ah, R2) + 0.35 * signal.lfilter(bm, am, R2)
peak = max(np.max(np.abs(L2)), np.max(np.abs(R2)))
L2, R2 = L2 / peak * 1.4, R2 / peak * 1.4
L2, R2 = np.tanh(L2) * 0.89, np.tanh(R2) * 0.89
# trim the tail and fade the ends for a clean loop
end = int(N_BARS * BAR * SR + 3 * SR)
L2, R2 = L2[:end], R2[:end]
fi, fo = int(0.05 * SR), int(3.0 * SR)
for ch in (L2, R2):
    ch[:fi] *= np.linspace(0, 1, fi)
    ch[-fo:] *= np.linspace(1, 0, fo) ** 2

from scipy.io import wavfile
out = np.stack([L2, R2], axis=1)
wavfile.write(sys.argv[1], SR, (out * 32767).astype(np.int16))
print("seconds", len(L2) / SR)
